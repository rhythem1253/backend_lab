const os = require("os")

// shows the type of os we are working with
console.log(os.platform())

// shows the type of os
console.log(os.type())

// return the os version
console.log(os.release())

// tells the cpu architecture
console.log(os.arch())

// Return the network name
console.log(os.hostname())

// return cpu information as an array of objects
console.log(os.cpus())

// tells the total ram available in bytes
console.log(os.totalmem())

// it shows the memory currently available
console.log(os.freemem())


